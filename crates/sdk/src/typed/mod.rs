//! typed 面的**运行时胶水**（M6）：过程宏生成的那几行代码落在这里。
//!
//! 宏只负责语法（脱糖、名字、声明），一切跨边界的行为都收敛到这两个模块：
//! - [`service`] —— 服务方法的 JSON 面：参数信封、返回值、错误映射、信封形状校验（G8）；
//! - [`events`] —— typed 事件的载荷编解码与 typed `next`。
//!
//! 为什么值得单独一层：typed 面只在 **T1**（进程内）类型安全，跨 ABI 一律走 JSON
//! （D2 的 `TypeId` 边界）。把 JSON 的细节钉在这两个模块里，跨边界行为就只有一处要审。

pub mod events;
pub mod service;
